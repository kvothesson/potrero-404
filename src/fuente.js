// Escribe texto en mayúsculas. esc = tamaño del píxel; sombra = color de la sombra dura de 1 píxel.
export function texto(ctx, str, x, y, { color = '#fff', esc = 1, alinear = 'izq', sombra = '#000' } = {}) {
  const s = String(str).toUpperCase();
  const ancho = s.length * 6 * esc - esc;
  let x0 = Math.round(alinear === 'centro' ? x - ancho / 2 : alinear === 'der' ? x - ancho : x);
  const y0 = Math.round(y);
  const pasada = (col, dx, dy) => {
    ctx.fillStyle = col;
    let cx = x0 + dx;
    for (const ch of s) {
      const g = G[ch] || G['?'];
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '1') ctx.fillRect(cx + c * esc, y0 + dy + r * esc, esc, esc);
      cx += 6 * esc;
    }
  };
  if (sombra) pasada(sombra, esc, esc);
  pasada(color, 0, 0);
  return ancho;
}
